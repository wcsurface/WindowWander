-- ROAD TRIP BINGO RAILWAY POSTGRESQL SCHEMA

-- USER ACCOUNTS & EXPLORER PROGRESS (PRIMARY SOURCE OF TRUTH)
CREATE TABLE IF NOT EXISTS users (
    id SERIAL PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    level INT DEFAULT 1,
    xp INT DEFAULT 0,
    earned_badges TEXT DEFAULT 'first_ride',
    streak_days INT DEFAULT 1,
    bingos_won INT DEFAULT 0,
    games_played INT DEFAULT 0,
    squares_found INT DEFAULT 0,
    last_play_date VARCHAR(20) DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- MULTIPLAYER ROOMS
CREATE TABLE IF NOT EXISTS game_rooms (
    id SERIAL PRIMARY KEY,
    room_code VARCHAR(4) UNIQUE NOT NULL,
    host_nickname VARCHAR(50) NOT NULL,
    deck_id VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN DEFAULT TRUE
);

-- ROOM PLAYERS
CREATE TABLE IF NOT EXISTS room_players (
    id SERIAL PRIMARY KEY,
    room_code VARCHAR(4) REFERENCES game_rooms(room_code) ON DELETE CASCADE,
    player_id VARCHAR(100) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    score INT DEFAULT 0,
    has_bingo BOOLEAN DEFAULT FALSE,
    joined_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- DISCOVERY FEED EVENTS
CREATE TABLE IF NOT EXISTS discovery_events (
    id SERIAL PRIMARY KEY,
    room_code VARCHAR(4) REFERENCES game_rooms(room_code) ON DELETE CASCADE,
    prompt_id VARCHAR(50) NOT NULL,
    claimed_by_nickname VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
