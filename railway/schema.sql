-- ROAD TRIP BINGO RAILWAY POSTGRESQL SCHEMA

CREATE TABLE IF NOT EXISTS game_rooms (
    id SERIAL PRIMARY KEY,
    room_code VARCHAR(4) UNIQUE NOT NULL,
    host_nickname VARCHAR(50) NOT NULL,
    deck_id VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS room_players (
    id SERIAL PRIMARY KEY,
    room_code VARCHAR(4) REFERENCES game_rooms(room_code) ON DELETE CASCADE,
    player_id VARCHAR(100) NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    score INT DEFAULT 0,
    has_bingo BOOLEAN DEFAULT FALSE,
    joined_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS discovery_events (
    id SERIAL PRIMARY KEY,
    room_code VARCHAR(4) REFERENCES game_rooms(room_code) ON DELETE CASCADE,
    prompt_id VARCHAR(50) NOT NULL,
    claimed_by_nickname VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
